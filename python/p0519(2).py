# 횟수가 정해져있거나, 1부터 10까지 등과 같이 범위가 정해져있는 경우에 사용

# 연속되는 숫자를 만들어 주는 시퀀스 자료형
# 시작하는 숫자(a)와 끝내는 숫자(b)를 지정하면
# a부터 b-1까지의 숫자를 만들어주는 시퀀스 자료형

print(range(10)) # 0부터 9까지의 숫자
print(range(1, 11)) # 1부터 10까지의 숫자
print(list(range(10))) # range는 시퀀스 자료형이지만, 리스트로 변환해서 출력해야 숫자들이 보임

