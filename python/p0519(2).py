# 다음은 while True:를 이용하여 shopping_list에 제약없이 물건을 담을 수 있는 프로그램을 만들어보세요!
# '구매' 를 입력하면 입력된 shopping_list를 출력합니다.
shopping_list = []

while True:
    product = input()
    if product == "구매":
        break
    shopping_list.append(product)

print(shopping_list)
