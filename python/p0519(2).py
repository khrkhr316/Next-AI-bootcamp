# 반복문

# 반복문의 필요성
# 1. 같은 코드를 여러 번 실행해야 하는 경우
# 2. 규칙적인 패턴이 존재하는 경우

# 파이썬에서 반복문은
# 어떠한 조건이나 범위 내에서 어떠한 명령을 반복적으로 실행할 때 사용되는 구문

# for문

# [1,2,3,4,5] 시퀀스에서
# 원소를 하나씩 가져와서 for
# 출력 print

# 원소로 반복하는 방법
# 시퀀스의 원소를 하나씩 변수에 넣어가면서 명령 실행

# for 변수 in 시퀀스:
#     <수행할 명령>     # 들여쓰기 !!!

sum = 0

for i in [1, 3, 5]:
    sum = sum + i

# 1 <- 0 + 1
# 1 <- 1 + 3
# 4 <- 4 + 5
# 최종값은 9

print(sum) # 9

# 명령이 len(시퀀스) 만큼 반복됨

length = 0

for i in [1, 3, 5]:
    length = length + 1

# 1 <- 0 + 1
# 2 <- 1 + 1
# 3 <- 2 + 1
# 최종값은 3

print(length) # 3


