# 1. 리스트 활용

# 자료 d를 리스트 마지막 원소 뒤에 추가
# 오직 한 개의 자료만 넣을 수 있음

a = []
b = ["a","b","c"]

a.append(1)
b.append("d")

print(a) # [1]
print(b) # ['a', 'b', 'c', 'd']

# 지정한 인덱스 위치 i에 자료 d를 삽입
# 오직 한 개의 자료만 넣을 수 있음

c = [1, 2, 3]
c.insert(1, "a")  # 인덱스 1에 "a" 삽입
print(c) # [1, 'a', 2, 3] = [0번째 원소, 1번째 원소, 2번째 원소, 3번째 원소]

# 처음 나오는 자료 d를 제거

my_list = [1, 2, 3, 2, 4]
my_list.remove(2)  # 처음 나오는 2를 제거
print(my_list) # [1, 3, 2, 4]

# 리스트 내의 자료들을 순서대로 정렬
# 숫자 자료는 오름차순, 문자열 자료는 사전 순으로 정렬(a부터 z까지, ㄱ부터 ㅎ까지)

e = [3, 1, 4, 2]
f = ["carrot", "apple", "banana"]

e.sort()  # 숫자 리스트를 오름차순으로 정렬
f.sort()  # 문자열 리스트를 사전 순으로 정렬

print(e) # [1, 2, 3, 4]
print(f) # ['apple', 'banana', 'carrot']

# 오름차순은 소괄호 안에 아무것도 넣지 않거나, reverse=False로 설정
# 내림차순은 reverse=True로 설정

