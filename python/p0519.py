# 시퀀스 자료형

# 순서가 있는 자료형
# 문자열, 리스트 등이 시퀀스 자료형에 속함

# 원소 간의 순서가 존재하기 때문에 인덱싱과 슬라이싱이 가능함

a = "Hello"
b = [1, 2, 3, 4, 5]

print(a[0]) # H
print(b[0]) # 1

# 인덱싱과 슬라이싱을 할 때
# 음수를 넣거나 자리를 비우는 것이 가능

print(a[-1]) # o
print(b[-1]) # 5
print(a[1:4]) # llo
print(b[1:4]) # [2, 3, 4]
print(a[1:]) # ello
print(b[1:]) # [2, 3, 4, 5]

# in 연산자로 시퀀스 안에 특정 자료가 있는지 확인할 수 있음

a = "Hello"
b = [1, 2, 3, 4, 5]

print("H" in a) # True
print(1 in b) # True
print("h" in a) # False
print(6 in b) # False

# len 함수를 이용하여 시퀀스 자료형의 길이를 구할 수 있음

print(len(a)) # 5
print(len(b)) # 5

# + 연산자를 이용하여 시퀀스 자료형을 서로 이어붙일 수 있음

a = "Hello"
b = "World"

c = a + " " + b
print(c) # Hello World

# * 연산자를 이용하여 시퀀스 자료형을 여러 번 반복할 수 있음

a = "Hello"
b = [1, 2, 3]

c = a * 3
d = b * 2

print(c) # HelloHelloHello
print(d) # [1, 2, 3, 1, 2, 3]

